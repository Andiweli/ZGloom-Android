void Hud::Render(SDL_Surface* surface, MapObject& player, Font& font, int lives)
{
	SDL_Rect dstrect;
	SDL_Rect srcrect;

	int scale = surface->h / 256;

	if (scale < 1) scale = 1;

	// Original-style top-left HUD layout.  Draw directly from the real
	// fixed embedded smallfont.bin in red.  This avoids per-game font
	// differences and never falls back to bigfont2.
	DrawHudText("HEALTH", 2, 4, surface, scale);
	DrawHudText("WEAPON", 2, 15, surface, scale);

	// GloomReforged-compatible life reserve at the top-right.  The embedded
	// smallfont contains the original red life/heart at zero-based slot 43
	// (the assembler calls it shape 44).  Anchor against the logical render
	// width so placement remains correct in both 320x256 and 455x256 modes.
	const int logicalWidth = surface->w / scale;
	DrawHudText("LIVES", logicalWidth - 84, 4, surface, scale);
	lives = std::max(0, std::min(5, lives));
	for (int i = 0; i < lives; ++i)
	{
		DrawHudGlyph(43, logicalWidth - 44 + i * 8, 4, surface, scale);
	}

	int hitpoints = player.data.ms.hitpoints;
	if (hitpoints < 0) hitpoints = 0;
	if (hitpoints > 25) hitpoints = 25;

	dstrect.x = 44 * scale;
	dstrect.y = 4 * scale;
	dstrect.w = (25 * 2 + 2) * scale;
	dstrect.h = 8 * scale;

	srcrect.x = 0;
	srcrect.y = 0;
	srcrect.w = 25 * 2 + 2;
	srcrect.h = 8;

	// No inactive healthbar background: draw only the active health units.
	srcrect.w = hitpoints * 2;
	dstrect.w = srcrect.w * scale;
	if (srcrect.w > 0)
	{
		SDL_BlitScaled(healthbaron, &srcrect, surface, &dstrect);
	}

	int weapon = player.data.ms.weapon;
	if (weapon < 0) weapon = 0;
	if (weapon > 4) weapon = 4;

	int weaponIcons = 6 - player.data.ms.reload;
	if (weaponIcons < 0) weaponIcons = 0;
	if (weaponIcons > 6) weaponIcons = 6;

	for (int i = 0; i < weaponIcons; i++)
	{
		dstrect.x = (44 + 10 * i) * scale;
		dstrect.y = 14 * scale;
		dstrect.w = weaponsprites[weapon]->w * scale;
		dstrect.h = weaponsprites[weapon]->h * scale;

		SDL_BlitScaled(weaponsprites[weapon], NULL, surface, &dstrect);
	}

	if (player.data.ms.messtimer < 0)
	{
		font.PrintMessage(messages[player.data.ms.mess], 40, surface, scale);
	}

	//GUN. This is largely guesswork, it's not in the available gloom deluxe source as far as I can tell. There's not even a reference to gun.bin

	if (gunshapes.size())
	{
		dstrect.x = surface->w / 2 - gunshapes[0].xh * scale;
		dstrect.y = surface->h - gunshapes[0].h*scale;
		dstrect.w = gunshapes[0].w*scale;
		dstrect.h = gunshapes[0].h*scale;

		if (player.data.ms.fired)
		{
			SDL_Rect bullrect;

			// G3 does not have fire anims?
			if (gunshapes.size() > 2)
			{
				int wepshape = 2 + (player.data.ms.weapon + 1) / 2;
				bullrect.x = (surface->w - gunshapes[wepshape].w*scale) / 2;
				bullrect.y = surface->h - gunshapes[wepshape].h*scale;
				bullrect.w = gunshapes[wepshape].w*scale;
				bullrect.h = gunshapes[wepshape].h*scale;

				int zoom = GloomMaths::RndW() & 3;

				bullrect.x -= zoom*scale;
				bullrect.y -= zoom*scale;
				bullrect.w += 2*zoom*scale;
				bullrect.h += 2*zoom*scale;

				SDL_BlitScaled(gunsurfaces[wepshape], NULL, surface, &bullrect);
			}


			dstrect.y += 10 * scale;
		}
		else if (player.data.ms.bounce)
		{
			int16_t camrots[4];
			uint8_t ang = (player.data.ms.bounce>>1) * 0xff;

			GloomMaths::GetCamRotRaw(ang, camrots);

			int32_t xoffset = camrots[1];

			xoffset <<= 5;

			xoffset >>= 16;

			dstrect.x += xoffset*scale;

			int32_t yoffset = xoffset/2;

			if (yoffset < 0) yoffset = -yoffset;

			dstrect.y -= yoffset*scale;
		}

		dstrect.y += 25 * scale;

		if (player.data.ms.invisible)
		{
			SDL_SetSurfaceBlendMode(gunsurfacesblend[player.data.ms.fired ? 1 : 0], SDL_BLENDMODE_MOD);
			SDL_BlitScaled(gunsurfacesblend[player.data.ms.fired ? 1 : 0], NULL, surface, &dstrect);
		}
		else
		{
			SDL_BlitScaled(gunsurfaces[player.data.ms.fired ? 1 : 0], NULL, surface, &dstrect);
		}
	}

	
	// --- Muzzle Flash (PC port from Vita 7.19): simple additive flash on fire ---
	static uint8_t s_mz_prev = 0;
	uint8_t __mz_cur = (uint8_t)player.data.ms.fired;
	if (__mz_cur > 0) {
		if (s_mz_prev == 0 || __mz_cur > s_mz_prev) {
			int __wep = player.data.ms.weapon; if (__wep < 0) __wep = 0; if (__wep > 4) __wep = 4;
			float __scale = 1.0f + 0.2f * (float)(__wep);
			MuzzleFlashFX::Get().SetScale(__scale);
			// Slightly warm off-white tint (match Vita default)
			MuzzleFlashFX::Get().SetTint(g_weapon_tint[__wep][0], g_weapon_tint[__wep][1], g_weapon_tint[__wep][2]);
			MuzzleFlashFX::Get().Trigger(1.0f, 1.0f);
		}
	} else {
		if (s_mz_prev > 0) { MuzzleFlashFX::Get().Disarm(); }
	}
	s_mz_prev = __mz_cur;
	// --- end muzzle flash port ---

	if (Config::GetDebug())
	{
		std::string pos = "position ";
		std::string fps = "FPS ";

		pos += std::to_string(player.x.GetInt());
		pos += ' ';
		pos += std::to_string(player.z.GetInt());
		pos += ' ';
		pos += std::to_string(player.data.ms.rotquick.GetInt());

		fps += std::to_string(Config::GetFPS());

		font.PrintMessage(pos, 0, surface, 1);
		font.PrintMessage(fps,10, surface, 1);
	}
}
