static bool HudLoadEmbeddedCrm2(const unsigned char* src, unsigned int srcSize, CrmFile& out)
{
	if (out.data)
	{
		std::free(out.data);
		out.data = nullptr;
	}
	out.size = 0;

	if (!src || srcSize == 0)
	{
		return false;
	}

	if (srcSize > 14 && GetSize((void*)src) != 0)
	{
		const unsigned int outSize = GetSize((void*)src);
		const unsigned int headroom = GetSecDist((void*)src);
		unsigned char* indata = static_cast<unsigned char*>(std::malloc(srcSize));
		unsigned char* outdata = static_cast<unsigned char*>(std::malloc(outSize + headroom));
		out.data = static_cast<unsigned char*>(std::malloc(outSize));
		if (!indata || !outdata || !out.data)
		{
			if (indata) std::free(indata);
			if (outdata) std::free(outdata);
			if (out.data) std::free(out.data);
			out.data = nullptr;
			return false;
		}

		std::memcpy(indata, src, srcSize);
		Decrunch(indata, outdata);
		std::memcpy(out.data, outdata, outSize);
		out.size = outSize;
		std::free(indata);
		std::free(outdata);
		return true;
	}

	out.data = static_cast<unsigned char*>(std::malloc(srcSize));
	if (!out.data)
	{
		return false;
	}
	std::memcpy(out.data, src, srcSize);
	out.size = srcSize;
	return true;
}

static uint16_t HudGet16(const uint8_t* p)
{
	return (static_cast<uint16_t>(p[0]) << 8) | static_cast<uint16_t>(p[1]);
}

static uint32_t HudGet32(const uint8_t* p)
{
	return (static_cast<uint32_t>(p[0]) << 24) |
	       (static_cast<uint32_t>(p[1]) << 16) |
	       (static_cast<uint32_t>(p[2]) << 8) |
	       (static_cast<uint32_t>(p[3]) << 0);
}

static uint32_t HudPaletteIndexToRed(const uint8_t* data, uint32_t size, uint32_t paletteOffset, uint32_t index)
{
	if (!data || index == 0)
	{
		return 0;
	}

	uint8_t brightness = 0xC0;
	const uint32_t pos = paletteOffset + index * 2;
	if (pos + 1 < size)
	{
		uint8_t r = (data[pos + 0] & 0x0F) << 4;
		uint8_t g = (data[pos + 1] >> 4) << 4;
		uint8_t b = (data[pos + 1] & 0x0F) << 4;
		brightness = r;
		if (g > brightness) brightness = g;
		if (b > brightness) brightness = b;
		if (brightness < 0x70) brightness = 0x70;
	}

	return 0xFF000000u | (static_cast<uint32_t>(brightness) << 16);
}

struct HudSmallFontCache
{
	SDL_Surface* glyphs[50];
	bool attempted;
	bool loaded;
	int advance;

	HudSmallFontCache()
	{
		for (int i = 0; i < 50; ++i) glyphs[i] = nullptr;
		attempted = false;
		loaded = false;
		advance = 6;
	}
};

static SDL_Surface* HudCreateGlyphSurface(int w, int h)
{
	if (w <= 0) w = 1;
	if (h <= 0) h = 1;
	SDL_Surface* s = SDL_CreateRGBSurface(0, w, h, 32, 0x00FF0000, 0x0000FF00, 0x000000FF, 0xFF000000);
	if (s)
	{
		SDL_SetSurfaceBlendMode(s, SDL_BLENDMODE_BLEND);
		SDL_FillRect(s, nullptr, 0x00000000);
	}
	return s;
}

static bool HudLoadCrmSmallFont(CrmFile& fontfile, HudSmallFontCache& out)
{
	if (!fontfile.data || fontfile.size < 4 + 50 * 4)
	{
		return false;
	}

	const uint8_t* data = fontfile.data;
	const uint32_t size = fontfile.size;
	const uint32_t paletteOffset = HudGet32(data + 0);
	if (paletteOffset >= size)
	{
		return false;
	}

	// Decrunched Gloom/Gloom Deluxe/Gloom 3 smallfont.bin uses the same
	// 7-bitplane glyph layout as Font::Load(), but Font::Load() does not
	// create 32-bit scaled glyphs.  Decode straight to ARGB here so Android
	// scaled blits are safe and the HUD never falls back to bigfont2.
	for (int i = 0; i < 50; ++i)
	{
		const uint32_t pos = HudGet32(data + 4 + 4 * i);
		if (pos + 8 >= size)
		{
			return false;
		}

		const uint32_t maskpos = pos + 8;
		const uint32_t modulo = HudGet16(data + pos + 4);
		const uint32_t width = modulo * 8;
		const uint32_t widthheight = HudGet16(data + pos + 6);
		uint32_t glyphHeight = (widthheight >> 6) / 7;
		if (width == 0 || glyphHeight == 0 || maskpos >= size)
		{
			return false;
		}

		SDL_Surface* glyph = HudCreateGlyphSurface(7, 8);
		if (!glyph)
		{
			return false;
		}

		for (uint32_t y = 0; y < 8; ++y)
		{
			for (uint32_t x = 0; x < 7; ++x)
			{
				uint32_t index = 0;
				if (y < glyphHeight && x < width)
				{
					for (uint32_t plane = 0; plane < 7; ++plane)
					{
						const uint32_t byteOffset = maskpos + (x + (y * 7 + plane) * width) / 8;
						if (byteOffset >= size)
						{
							continue;
						}
						const uint8_t thebyte = data[byteOffset];
						if (thebyte & (1 << (7 - (x % 8))))
						{
							index |= (1u << plane);
						}
					}
				}

				uint32_t* dst = reinterpret_cast<uint32_t*>(reinterpret_cast<uint8_t*>(glyph->pixels) + y * glyph->pitch) + x;
				*dst = HudPaletteIndexToRed(data, size, paletteOffset, index);
			}
		}

		out.glyphs[i] = glyph;
	}

	out.advance = 6;
	return true;
}

static bool HudLoadRawShapeSmallFont(CrmFile& fontfile, HudSmallFontCache& out)
{
	if (!fontfile.data || fontfile.size < 12)
	{
		return false;
	}

	const uint8_t* data = fontfile.data;
	const uint32_t size = fontfile.size;
	const uint32_t shift = HudGet16(data + 0);
	if (shift > 8)
	{
		return false;
	}
	const uint32_t frames = static_cast<uint32_t>(HudGet16(data + 2)) << shift;
	const uint32_t paletteOffset = HudGet32(data + 8);
	if (frames < 50 || frames > 256 || paletteOffset >= size || 12 + frames * 4 > size)
	{
		return false;
	}

	// Zombie Massacre's stuf/smallfont.bin is an unpacked Shape/Graphic file,
	// not the CrM2 font layout.  Load the glyph shapes directly and tint them red.
	for (uint32_t i = 0; i < 50; ++i)
	{
		const uint32_t off = HudGet32(data + 12 + i * 4);
		if (off + 8 >= size)
		{
			return false;
		}

		const uint32_t w = HudGet16(data + off + 4);
		const uint32_t h = HudGet16(data + off + 6);
		if (w == 0 || h == 0 || w > 32 || h > 32 || off + 8 + w * h > size)
		{
			return false;
		}

		SDL_Surface* glyph = HudCreateGlyphSurface(static_cast<int>(w), static_cast<int>(h));
		if (!glyph)
		{
			return false;
		}

		for (uint32_t y = 0; y < h; ++y)
		{
			for (uint32_t x = 0; x < w; ++x)
			{
				// Shape data is column-major in this codebase: y + x*h.
				const uint32_t index = data[off + 8 + y + x * h];
				uint32_t* dst = reinterpret_cast<uint32_t*>(reinterpret_cast<uint8_t*>(glyph->pixels) + y * glyph->pitch) + x;
				*dst = HudPaletteIndexToRed(data, size, paletteOffset, index);
			}
		}

		out.glyphs[i] = glyph;
	}

	out.advance = 6;
	return true;
}

static HudSmallFontCache& GetHudSmallFont()
{
	static HudSmallFontCache cache;
	if (!cache.attempted)
	{
		cache.attempted = true;
		CrmFile fontfile;
		// Fixed embedded HUD font: do not depend on misc/smallfont.bin or
		// Zombie Massacre's stuf/smallfont.bin.  This keeps HEALTH/WEAPON
		// identical across all installed Gloom-engine games and avoids the
		// incompatible raw-shape smallfont path.
		if (HudLoadEmbeddedCrm2(kEmbeddedHudSmallfontCrm2, kEmbeddedHudSmallfontCrm2Size, fontfile))
		{
			cache.loaded = HudLoadCrmSmallFont(fontfile, cache);
		}
	}
	return cache;
}

static void DrawHudText(const char* text, int x, int y, SDL_Surface* dest, int scale)
{
	if (!text || !dest) return;
	HudSmallFontCache& font = GetHudSmallFont();
	if (!font.loaded) return;

	int drawX = x * scale;
	const int drawY = y * scale;
	const int advance = font.advance * scale;

	for (const char* c = text; *c; ++c)
	{
		int glyph = -1;
		if (*c >= '0' && *c <= '9')
		{
			glyph = *c - '0';
		}
		else if (*c >= 'A' && *c <= 'Z')
		{
			glyph = *c - 'A' + 10;
		}
		else if (*c >= 'a' && *c <= 'z')
		{
			glyph = *c - 'a' + 10;
		}
		else if (*c == '!')
		{
			glyph = 36;
		}
		else if (*c == '.')
		{
			glyph = 37;
		}
		else if (*c == ':')
		{
			glyph = 38;
		}

		if (glyph >= 0 && glyph < 50 && font.glyphs[glyph])
		{
			SDL_Rect dstrect;
			dstrect.x = drawX;
			dstrect.y = drawY;
			dstrect.w = font.glyphs[glyph]->w * scale;
			dstrect.h = font.glyphs[glyph]->h * scale;
			SDL_BlitScaled(font.glyphs[glyph], nullptr, dest, &dstrect);
		}

		drawX += advance;
	}
}

static void DrawHudGlyph(int glyphIndex, int x, int y, SDL_Surface* dest, int scale)
{
	if (!dest || scale < 1) return;
	HudSmallFontCache& font = GetHudSmallFont();
	if (!font.loaded || glyphIndex < 0 || glyphIndex >= 50 || !font.glyphs[glyphIndex])
		return;

	SDL_Rect dstrect;
	dstrect.x = x * scale;
	dstrect.y = y * scale;
	dstrect.w = font.glyphs[glyphIndex]->w * scale;
	dstrect.h = font.glyphs[glyphIndex]->h * scale;
	SDL_BlitScaled(font.glyphs[glyphIndex], nullptr, dest, &dstrect);
}

static float g_weapon_tint[5][3] = {
    {1.0f, 0.97f, 0.94f},
    {1.0f, 0.97f, 0.94f},
    {1.0f, 0.97f, 0.94f},
    {1.0f, 0.97f, 0.94f},
    {1.0f, 0.97f, 0.94f}
};

static inline void ComputeWeaponTintsFromIcons(SDL_Surface* icons[5]) {
    for (int i = 0; i < 5; ++i) {
        SDL_Surface* s = icons[i];
        if (!s) continue;
        uint64_t sumR = 0, sumG = 0, sumB = 0; int count = 0;
        for (int y = 0; y < s->h; ++y) {
            uint32_t* row = (uint32_t*)((uint8_t*)s->pixels + y * s->pitch);
            for (int x = 0; x < s->w; ++x) {
                uint32_t p = row[x];
                if ((p & 0xFF000000u) == 0) continue; // skip transparent
                sumR += (p >> 16) & 0xFFu;
                sumG += (p >> 8)  & 0xFFu;
                sumB += (p >> 0)  & 0xFFu;
                ++count;
            }
        }
        if (count > 0) {
            float r = (float)sumR / (255.0f * (float)count);
            float g = (float)sumG / (255.0f * (float)count);
            float b = (float)sumB / (255.0f * (float)count);
            float m = r; if (g > m) m = g; if (b > m) m = b; if (m < 1e-4f) m = 1.0f;
            g_weapon_tint[i][0] = r / m;
            g_weapon_tint[i][1] = g / m;
            g_weapon_tint[i][2] = b / m;
        }
    }
}

// Export weapon tint for renderer effects (used by renderer.cpp)
void Hud_GetWeaponTint(int wepIndex, float& r, float& g, float& b)
{
    if (wepIndex < 0) wepIndex = 0;
    if (wepIndex > 4) wepIndex = 4;
    r = g_weapon_tint[wepIndex][0];
    g = g_weapon_tint[wepIndex][1];
    b = g_weapon_tint[wepIndex][2];
}


